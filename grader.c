static void t_reverseArray(void)
{
    int odd[7]  = {-1, 1, 2, 3, 4, 5, -1};
    int oddE[7] = {-1, 5, 4, 3, 2, 1, -1};
    int ev[6]   = {-1, 1, 2, 3, 4, -1};
    int evE[6]  = {-1, 4, 3, 2, 1, -1};
    int one[3]  = {-1, 9, -1};
    int oneE[3] = {-1, 9, -1};

    reverseArray(odd + 1, 5);
    checkf(arrEq(odd, oddE, 7), 0.75, "reverse {1,2,3,4,5}: expected {5,4,3,2,1} and nothing outside; array is now %s (with guard values -1 at both ends)", A(odd, 7));

    reverseArray(ev + 1, 4);
    checkf(arrEq(ev, evE, 6), 0.75, "reverse {1,2,3,4}: expected {4,3,2,1}; array is now %s", A(ev, 6));

    reverseArray(one + 1, 1);
    reverseArray(NULL, 3);
    checkf(arrEq(one, oneE, 3), 0.50, "n=1 must change nothing, NULL array must not crash");
}

