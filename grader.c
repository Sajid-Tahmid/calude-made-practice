/* ============================================================
 * TRACKED ALLOCATOR
 * Every malloc/free inside exam.c is redirected here.
 * ============================================================
 */

#define MAX_TRACK 8192

static void  *g_ptr[MAX_TRACK];
static size_t g_sz[MAX_TRACK];
static int    g_live = 0;      /* number of blocks currently allocated */
static int    g_badFree = 0;   /* invalid / double frees seen */

static int t_find(const void *p)
{
    int i;
    for (i = 0; i < g_live; i++)
        if (g_ptr[i] == p) return i;
    return -1;
}

static void *t_malloc(size_t n)
{
    void *p = malloc(n ? n : 1);
    if (!p) return NULL;
    memset(p, 0xAB, n);                      /* uninitialised memory is NOT zero */
    if (g_live < MAX_TRACK) {
        g_ptr[g_live] = p;
        g_sz[g_live] = n;
        g_live++;
    }
    return p;
}

static void *t_calloc(size_t a, size_t b)
{
    void *p = t_malloc(a * b);
    if (p) memset(p, 0, a * b);
    return p;
}

static void t_free(void *p)
{
    int i;
    if (!p) return;
    i = t_find(p);
    if (i < 0) { g_badFree++; return; }      /* never allocated, or already freed */
    memset(p, 0xDD, g_sz[i]);                /* poison: use-after-free will blow up */
    free(p);
    g_live--;
    g_ptr[i] = g_ptr[g_live];
    g_sz[i] = g_sz[g_live];
}

static void *t_realloc(void *p, size_t n)
{
    int i;
    void *q;
    if (!p) return t_malloc(n);
    i = t_find(p);
    if (i < 0) { g_badFree++; return NULL; }
    q = realloc(p, n);
    if (q) { g_ptr[i] = q; g_sz[i] = n; }
    return q;
}

static int isLive(const void *p)
{
    return p != NULL && t_find(p) >= 0;
}

#define malloc(n)      t_malloc(n)
#define calloc(a, b)   t_calloc(a, b)
#define realloc(p, n)  t_realloc(p, n)
#define free(p)        t_free(p)

