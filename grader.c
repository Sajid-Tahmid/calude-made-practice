static void mkSet(Book *bs, const float *prices, int n)
{
    int i;
    char t[16];
    for (i = 0; i < n; i++) {
        sprintf(t, "T%d", i + 1);
        bs[i] = mkBook(i + 1, t, prices[i], i + 1);
    }
}

/* every book must still be a consistent "T<id>" book (whole struct moved) */
static int setIntact(const Book *bs, int n, const float *prices)
{
    int i;
    char t[16];
    for (i = 0; i < n; i++) {
        int id = bs[i].id;
        if (id < 1 || id > 50) return 0;
        sprintf(t, "T%d", id);
        if (strcmp(bs[i].title, t) != 0) return 0;
        if (bs[i].copies != id) return 0;
        if (bs[i].price != prices[id - 1]) return 0;
    }
    return 1;
}

