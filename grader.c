typedef void (*TestFn)(void);

static double f_got, f_sum, f_soft;
static char   f_fail[8192];
static char   f_last[256];

static double p_got, p_max;     /* current part */
static double t_got, t_max;     /* whole exam */
static const char *p_title = NULL;

static void checkf(int cond, double w, const char *fmt, ...)
{
    char msg[512];
    char line[640];
    va_list ap;

    va_start(ap, fmt);
    vsnprintf(msg, sizeof msg, fmt, ap);
    va_end(ap);

    f_sum += w;
    if (cond) {
        f_got += w;
        strncpy(f_last, msg, sizeof f_last - 1);
        f_last[sizeof f_last - 1] = '\0';
    } else {
        snprintf(line, sizeof line, "        [-%.2f] %s\n", w, msg);
        strncat(f_fail, line, sizeof f_fail - strlen(f_fail) - 1);
    }
}

/* "must not crash" style checks: they only count once the function has
 * earned at least one real mark, so an empty TODO cannot collect them. */
static void softf(double w, const char *fmt, ...)
{
    (void)fmt;
    f_sum += w;
    f_soft += w;
}

static void endSection(void)
{
    if (p_title) {
        printf("  ---- %s: %.2f / %.2f ----\n", p_title, p_got, p_max);
    }
}

static void section(const char *title)
{
    endSection();
    p_title = title;
    p_got = 0;
    p_max = 0;
    printf("\n%s\n", title);
}

/* ---- detect functions that still contain the "TODO" placeholder ---- */

static char *g_src = NULL;

static void loadSource(void)
{
    FILE *f = fopen("exam.c", "rb");
    long n;
    if (!f) return;
    fseek(f, 0, SEEK_END);
    n = ftell(f);
    fseek(f, 0, SEEK_SET);
    g_src = (char *)malloc(n + 1);
    if (g_src) {
        n = (long)fread(g_src, 1, n, f);
        g_src[n] = '\0';
    }
    fclose(f);
}

static int isStub(const char *name)
{
    const char *p, *q, *body, *end;
    size_t len = strlen(name);
    char *tmp;
    int found = 0;

    if (!g_src) return 0;
    for (p = g_src; (p = strstr(p, name)) != NULL; p += len) {
        if (p > g_src && (p[-1] == '_' || (p[-1] >= 'a' && p[-1] <= 'z') ||
                          (p[-1] >= 'A' && p[-1] <= 'Z') || (p[-1] >= '0' && p[-1] <= '9')))
            continue;
        q = p + len;
        while (*q == ' ') q++;
        if (*q != '(') continue;
        {
            int depth = 0;
            while (*q) {
                if (*q == '(') depth++;
                else if (*q == ')' && --depth == 0) { q++; break; }
                q++;
            }
        }
        while (*q == ' ' || *q == '\n' || *q == '\r' || *q == '\t') q++;
        if (*q != '{') continue;
        body = q;
        end = strstr(body, "\n}");
        if (!end) end = body + strlen(body);
        tmp = (char *)malloc(end - body + 1);
        if (!tmp) return 0;
        memcpy(tmp, body, end - body);
        tmp[end - body] = '\0';
        found = strstr(tmp, "TODO") != NULL;
        free(tmp);
        return found;
    }
    return 0;
}

static void run(const char *name, double marks, TestFn fn)
{
    int badBefore = g_badFree;
    volatile int crashed = 0;
    double got;
    double diff;

    if (isStub(name)) {
        printf("  [ 0.00 / %5.2f]  %s\n", marks, name);
        printf("        not implemented yet (the body still contains /* TODO */)\n");
        p_max += marks;
        t_max += marks;
        return;
    }

    f_got = 0;
    f_sum = 0;
    f_soft = 0;
    f_fail[0] = '\0';
    f_last[0] = '\0';
    g_sig = 0;

    installHandlers();
    if (SETJ(g_jb) == 0) {
        g_active = 1;
#ifdef SIGALRM
        alarm(3);
#endif
        fn();
    } else {
        crashed = 1;
    }
    g_active = 0;
#ifdef SIGALRM
    alarm(0);
#endif

    got = f_got;
    if (f_got > 1e-9) got += f_soft;
    if (crashed || g_badFree > badBefore) got = 0;
    if (got > marks) got = marks;

    printf("  [%5.2f / %5.2f]  %s\n", got, marks, name);
    if (crashed) {
        printf("        !! CRASHED: %s  ->  0 marks for this function\n", sigName(g_sig));
        printf("        last check that passed: %s\n", f_last[0] ? f_last : "(none)");
        printf("        typical causes: dereferencing NULL / garbage pointer, reading a\n");
        printf("        node after free(), writing past the end of an array, endless loop\n");
    } else if (g_badFree > badBefore) {
        printf("        !! free() on a pointer that was not returned by malloc, or freed\n");
        printf("        twice  ->  0 marks for this function\n");
    }
    printf("%s", f_fail);

    diff = f_sum - marks;
    if (diff < 0) diff = -diff;
    if (!crashed && diff > 1e-6)
        printf("        (grader note: weights add up to %.2f, declared %.2f)\n", f_sum, marks);

    p_got += got;
    p_max += marks;
    t_got += got;
    t_max += marks;
}


