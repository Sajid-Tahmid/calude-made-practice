/* ============================================================
 * CRASH / TIMEOUT PROTECTION
 * ============================================================
 */

#ifdef _WIN32
typedef jmp_buf JB;
#define SETJ(b)  setjmp(b)
#define LONGJ(b) longjmp(b, 1)
#else
typedef sigjmp_buf JB;
#define SETJ(b)  sigsetjmp(b, 1)
#define LONGJ(b) siglongjmp(b, 1)
#endif

static JB g_jb;
static volatile sig_atomic_t g_sig = 0;
static volatile sig_atomic_t g_active = 0;

static void onSignal(int s)
{
    if (g_active) {
        g_sig = s;
        LONGJ(g_jb);
    }
    signal(s, SIG_DFL);
    raise(s);
}

static void installHandlers(void)
{
    signal(SIGSEGV, onSignal);
    signal(SIGFPE, onSignal);
    signal(SIGILL, onSignal);
    signal(SIGABRT, onSignal);
#ifdef SIGBUS
    signal(SIGBUS, onSignal);
#endif
#ifdef SIGALRM
    signal(SIGALRM, onSignal);
#endif
}

static const char *sigName(int s)
{
    if (s == SIGSEGV) return "segmentation fault";
    if (s == SIGFPE)  return "arithmetic error / divide by zero";
    if (s == SIGILL)  return "illegal instruction";
    if (s == SIGABRT) return "abort (heap corruption?)";
#ifdef SIGBUS
    if (s == SIGBUS)  return "bus error";
#endif
#ifdef SIGALRM
    if (s == SIGALRM) return "timeout, probably an infinite loop";
#endif
    return "unknown signal";
}


