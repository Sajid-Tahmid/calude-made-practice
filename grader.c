static const char *A(const int *a, int n)
{
    static char buf[4][160];
    static int k = 0;
    char *b = buf[k = (k + 1) % 4];
    int i, len = 0;
    b[0] = '\0';
    if (!a) return "NULL";
    len += snprintf(b + len, 160 - len, "{");
    for (i = 0; i < n && len < 140; i++)
        len += snprintf(b + len, 160 - len, "%s%d", i ? ", " : "", a[i]);
    snprintf(b + len, 160 - len, "}");
    return b;
}

static int arrEq(const int *a, const int *b, int n)
{
    int i;
    for (i = 0; i < n; i++)
        if (a[i] != b[i]) return 0;
    return 1;
}

static const char *S(const char *s)
{
    static char buf[4][100];
    static int k = 0;
    char *b = buf[k = (k + 1) % 4];
    if (!s) return "NULL";
    snprintf(b, 100, "\"%s\"", s);
    return b;
}

static int sgn(int x) { return x < 0 ? -1 : (x > 0 ? 1 : 0); }

/* ---- linked list helpers (nodes come from the tracked allocator) ---- */

static Node *buildList(const int *v, int n, Node **nodes)
{
    Node *head = NULL, *tail = NULL;
    int i;
    for (i = 0; i < n; i++) {
        Node *nd = (Node *)t_malloc(sizeof(Node));
        nd->value = v[i];
        nd->next = NULL;
        if (tail) tail->next = nd; else head = nd;
        tail = nd;
        if (nodes) nodes[i] = nd;
    }
    return head;
}

static int listIs(const Node *h, const int *v, int n)
{
    int i;
    for (i = 0; i < n; i++) {
        if (!h || h->value != v[i]) return 0;
        h = h->next;
    }
    return h == NULL;
}

static const char *L(const Node *h)
{
    static char buf[4][160];
    static int k = 0;
    char *b = buf[k = (k + 1) % 4];
    int len = 0, steps = 0;
    b[0] = '\0';
    if (!h) return "NULL (empty list)";
    while (h && steps < 10 && len < 130) {
        len += snprintf(b + len, 160 - len, "%d -> ", h->value);
        h = h->next;
        steps++;
    }
    snprintf(b + len, 160 - len, h ? "..." : "NULL");
    return b;
}

static void freeAll(Node *h)
{
    int guard = 0;
    while (h && guard < 1000) {
        Node *nx = h->next;
        if (isLive(h)) t_free(h);
        h = nx;
        guard++;
    }
}

/* ---- matrix helpers ---- */

static int **gmatrix(int rows, int cols)
{
    int **m = (int **)t_malloc(rows * sizeof(int *));
    int i, j;
    for (i = 0; i < rows; i++) {
        m[i] = (int *)t_malloc(cols * sizeof(int));
        for (j = 0; j < cols; j++) m[i][j] = i * cols + j;
    }
    return m;
}

static void gfreeMatrix(int **m, int rows)
{
    int i;
    if (!m) return;
    for (i = 0; i < rows; i++)
        if (isLive(m[i])) t_free(m[i]);
    if (isLive(m)) t_free(m);
}

