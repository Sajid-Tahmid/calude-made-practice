/*
 * ============================================================
 * grader.c  -  automatic grader for exam.c  (70 marks)
 * ============================================================
 *
 * Put this file next to exam.c, then:
 *
 *     gcc grader.c -o grader
 *     ./grader                 (Windows: grader.exe)
 *
 * What it does
 *   - runs every function with several test cases and gives
 *     partial marks for each check that passes
 *   - tells you which check failed and what it expected
 *   - catches crashes (segfault) and infinite loops, and gives
 *     that function 0 marks instead of killing the whole grader
 *   - counts malloc/free: leaks, double free, freeing a pointer
 *     that never came from malloc, and use-after-free are detected
 *
 * Do not edit this file.
 */

