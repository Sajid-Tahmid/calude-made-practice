static void t_swapInts(void)
{
    int a = 3, b = 7, x = 5;

    swapInts(&a, &b);
    checkf(a == 7 && b == 3, 0.50, "swapInts(&a,&b) with a=3,b=7 should give a=7,b=3 (got a=%d,b=%d)", a, b);

    swapInts(&x, &x);
    checkf(x == 5, 0.25, "swapInts(&x,&x) must leave x unchanged (got %d); XOR-swap tricks break here", x);

    swapInts(NULL, &x);
    swapInts(&x, NULL);
    checkf(x == 5, 0.25, "a NULL pointer must be ignored: no crash, no change");
}

static void t_swapPointers(void)
{
    int x = 10, y = 20;
    int *p = &x, *q = &y;

    swapPointers(&p, &q);
    checkf(p == &y && q == &x, 0.75, "after swapPointers(&p,&q): p should point to y and q to x");
    checkf(x == 10 && y == 20, 0.25, "x and y must NOT change (x=%d y=%d): swap the POINTERS, not the values", x, y);
}

static void t_minMax(void)
{
    int a[5] = {4, -2, 9, 9, 0};
    int one[1] = {7};
    int mn = 100, mx = -100, r;

    r = minMax(a, 5, &mn, &mx);
    checkf(r == 1, 0.25, "minMax on a valid array must return 1 (got %d)", r);
    checkf(mn == -2 && mx == 9, 0.75, "minMax(%s) should give min=-2 max=9 (got min=%d max=%d)", A(a, 5), mn, mx);

    mn = 0; mx = 0;
    r = minMax(one, 1, &mn, &mx);
    checkf(r == 1 && mn == 7 && mx == 7, 0.50, "single element {7}: min=max=7 (got r=%d min=%d max=%d)", r, mn, mx);

    mn = 111; mx = 222;
    r = minMax(a, 0, &mn, &mx);
    checkf(r == 0 && mn == 111 && mx == 222, 0.25, "n=0 must return 0 and leave the outputs untouched");

    r = minMax(a, 5, NULL, &mx);
    checkf(r == 0, 0.25, "NULL output pointer must return 0 (no crash)");
}

